"""Protocols that decouple the packages.

- StateRepository: persistence used by the mcp-server (InMemory for tests, DynamoDB in AWS).
- KnowledgeBase: method content used by the mcp-server (local disk or S3).
- ToolGateway: what the chat-service uses to reach the tools (remote MCP or in-process).
"""

from typing import Protocol

from vv_contracts.common import FactKind, FindingArea, LayerId, TemplateKind
from vv_contracts.kb import LayerSpec
from vv_contracts.state import (
    Baseline,
    EssentialCore,
    Evaluation,
    Fact,
    Gap,
    GapStatus,
    PreCore,
    PublicContextRecord,
    Review,
    Session,
    SessionState,
    StageProgress,
    StoredSynthesis,
    Turn,
)
from vv_contracts.tools import (
    Ack,
    CheckOutputIn,
    CheckOutputOut,
    CreateSessionIn,
    CreateSessionOut,
    GetLayerSpecIn,
    GetMethodGuideIn,
    GetMethodGuideOut,
    GetQuestionFromPoolIn,
    GetQuestionFromPoolOut,
    GetSessionStateIn,
    GetSynthesisTemplateIn,
    GetSynthesisTemplateOut,
    ListFactsIn,
    ListFactsOut,
    ListGapsIn,
    ListGapsOut,
    ReadPublicSiteIn,
    ReadPublicSiteOut,
    SaveBaselineIn,
    SaveCoreIn,
    SaveFactIn,
    SaveFactOut,
    SaveGapIn,
    SaveGapOut,
    SavePreCoreIn,
    SavePublicContextIn,
    SaveReviewIn,
    SaveSynthesisIn,
    SaveSynthesisOut,
    SaveTurnIn,
    SaveTurnOut,
    UpdateGapIn,
    UpdateSessionIn,
    UpdateStageProgressIn,
)


class StateRepository(Protocol):
    def get_state(self, session_id: str) -> SessionState | None: ...
    def put_session(self, session: Session) -> None: ...
    def save_baseline(self, session_id: str, baseline: Baseline) -> None: ...
    def save_public_context(self, session_id: str, context: PublicContextRecord) -> None: ...
    def save_turn(self, session_id: str, turn: Turn) -> int: ...
    def update_stage_progress(self, session_id: str, progress: StageProgress) -> None: ...
    def save_fact(self, session_id: str, fact: Fact) -> str: ...
    def list_facts(
        self,
        session_id: str,
        layer_id: LayerId | None = None,
        finding_area: FindingArea | None = None,
        kind: FactKind | None = None,
    ) -> list[Fact]: ...
    def save_gap(self, session_id: str, gap: Gap) -> str: ...
    def list_gaps(
        self, session_id: str, layer_id: LayerId | None = None, status: GapStatus | None = None
    ) -> list[Gap]: ...
    def update_gap(
        self, session_id: str, gap_id: str, status: GapStatus, fact_id: str | None = None
    ) -> None: ...
    def save_synthesis(self, session_id: str, synthesis: StoredSynthesis) -> int: ...
    def latest_synthesis(self, session_id: str, layer_id: LayerId) -> StoredSynthesis | None: ...
    def save_review(self, session_id: str, review: Review) -> None: ...
    def save_pre_core(self, session_id: str, pre_core: PreCore) -> None: ...
    def save_core(self, session_id: str, core: EssentialCore) -> None: ...
    def save_evaluation(self, session_id: str, evaluation: Evaluation) -> None: ...


class KnowledgeBase(Protocol):
    @property
    def version(self) -> str: ...
    def get_layer_spec(self, layer_id: LayerId) -> LayerSpec: ...
    def get_synthesis_template(self, kind: TemplateKind) -> str: ...
    def get_method_guide(self, quadrant: FindingArea | None = None) -> str: ...


class ToolGateway(Protocol):
    """One async method per MCP tool; argument and result are the contracts in `tools`."""

    async def create_session(self, req: CreateSessionIn) -> CreateSessionOut: ...
    async def update_session(self, req: UpdateSessionIn) -> Ack: ...
    async def save_baseline(self, req: SaveBaselineIn) -> Ack: ...
    async def save_public_context(self, req: SavePublicContextIn) -> Ack: ...
    async def get_session_state(self, req: GetSessionStateIn) -> SessionState: ...
    async def save_turn(self, req: SaveTurnIn) -> SaveTurnOut: ...
    async def update_stage_progress(self, req: UpdateStageProgressIn) -> Ack: ...
    async def save_fact(self, req: SaveFactIn) -> SaveFactOut: ...
    async def list_facts(self, req: ListFactsIn) -> ListFactsOut: ...
    async def save_gap(self, req: SaveGapIn) -> SaveGapOut: ...
    async def list_gaps(self, req: ListGapsIn) -> ListGapsOut: ...
    async def update_gap(self, req: UpdateGapIn) -> Ack: ...
    async def get_layer_spec(self, req: GetLayerSpecIn) -> LayerSpec: ...
    async def get_question_from_pool(
        self, req: GetQuestionFromPoolIn
    ) -> GetQuestionFromPoolOut: ...
    async def get_synthesis_template(
        self, req: GetSynthesisTemplateIn
    ) -> GetSynthesisTemplateOut: ...
    async def get_method_guide(self, req: GetMethodGuideIn) -> GetMethodGuideOut: ...
    async def save_synthesis(self, req: SaveSynthesisIn) -> SaveSynthesisOut: ...
    async def save_review(self, req: SaveReviewIn) -> Ack: ...
    async def save_pre_core(self, req: SavePreCoreIn) -> Ack: ...
    async def save_core(self, req: SaveCoreIn) -> Ack: ...
    async def check_output(self, req: CheckOutputIn) -> CheckOutputOut: ...
    async def read_public_site(self, req: ReadPublicSiteIn) -> ReadPublicSiteOut: ...
